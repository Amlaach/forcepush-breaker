"""
Git Object Database Forensics Engine.

Discovers dangling commits, unreachable trees, and orphaned blobs in local .git repositories.
Recovers commit metadata (author, timestamp, commit message) and reconstructed file diffs
using high-performance batch stream processing.
"""

from __future__ import annotations

import io
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple


@dataclass
class AIAgentAttribution:
    is_ai_agent: bool = False
    agent_name: Optional[str] = None
    confidence: float = 0.0
    evidence: List[str] = field(default_factory=list)


def detect_ai_agent(
    author: str = "",
    committer: str = "",
    message: str = "",
    diff_content: str = "",
) -> AIAgentAttribution:
    """Analyzes commit metadata (author, committer, commit message, Co-Authored-By trailers)

    to detect if a dangling commit was authored by an AI coding agent (Claude Code, Cursor,
    Devin, GitHub Copilot, Aider, OpenHands, etc.).
    """
    author_lower = (author or "").lower()
    committer_lower = (committer or "").lower()
    msg_lower = (message or "").lower()
    combined_meta = f"{author_lower} {committer_lower}"
    evidence: List[str] = []

    # 1. Claude Code / Anthropic
    if any(k in combined_meta for k in ["anthropic", "noreply@anthropic.com", "claude"]):
        evidence.append(f"Author metadata matched Claude: {author}")
    if re.search(r"co-authored-by:.*claude.*<noreply@anthropic\.com>", msg_lower):
        evidence.append("Co-Authored-By trailer identified Claude Code")
    elif "claude code" in msg_lower or "assisted by claude" in msg_lower or "generated by claude" in msg_lower:
        evidence.append("Commit message explicitly attributes Claude")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="Claude Code", confidence=0.95, evidence=evidence)

    # 2. Cursor
    if "cursor" in combined_meta or "anysphere" in combined_meta:
        evidence.append(f"Author metadata matched Cursor: {author}")
    if re.search(r"co-authored-by:.*cursor", msg_lower):
        evidence.append("Co-Authored-By trailer identified Cursor")
    elif "generated by cursor" in msg_lower or "cursor ai" in msg_lower or "cursor agent" in msg_lower:
        evidence.append("Commit message contains Cursor signature")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="Cursor", confidence=0.95, evidence=evidence)

    # 3. Devin
    if "devin" in combined_meta or "cognition" in combined_meta:
        evidence.append(f"Author metadata matched Devin: {author}")
    if re.search(r"co-authored-by:.*devin", msg_lower):
        evidence.append("Co-Authored-By trailer identified Devin")
    elif "devin session" in msg_lower or msg_lower.startswith("devin:"):
        evidence.append("Commit message matches Devin session signature")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="Devin", confidence=0.95, evidence=evidence)

    # 4. GitHub Copilot
    if "copilot" in combined_meta or "github-copilot" in combined_meta:
        evidence.append(f"Author metadata matched GitHub Copilot: {author}")
    if re.search(r"co-authored-by:.*copilot", msg_lower):
        evidence.append("Co-Authored-By trailer identified GitHub Copilot")
    elif "generated by copilot" in msg_lower or "copilot workspace" in msg_lower:
        evidence.append("Commit message references Copilot signature")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="GitHub Copilot", confidence=0.90, evidence=evidence)

    # 5. Aider
    if "aider" in combined_meta or "aider.chat" in combined_meta:
        evidence.append(f"Author metadata matched Aider: {author}")
    if re.search(r"co-authored-by:.*aider", msg_lower):
        evidence.append("Co-Authored-By trailer identified Aider")
    elif msg_lower.startswith("aider:") or "assisted by aider" in msg_lower:
        evidence.append("Commit message formatted by Aider CLI")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="Aider", confidence=0.95, evidence=evidence)

    # 6. OpenHands / OpenDevin
    if any(k in combined_meta for k in ["openhands", "all-hands", "opendevin"]):
        evidence.append(f"Author metadata matched OpenHands: {author}")
    if re.search(r"co-authored-by:.*(openhands|opendevin)", msg_lower):
        evidence.append("Co-Authored-By trailer identified OpenHands")
    elif "openhands" in msg_lower or "opendevin" in msg_lower:
        evidence.append("Commit message matches OpenHands automated signature")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="OpenHands", confidence=0.95, evidence=evidence)

    # 7. Generic AI Agent / LLM
    if any(k in combined_meta for k in ["chatgpt", "openai-bot"]):
        evidence.append(f"Author metadata matched AI agent: {author}")
    if "co-authored-by:.*chatgpt" in msg_lower or "generated by chatgpt" in msg_lower:
        evidence.append("Attributed to ChatGPT")
    if evidence:
        return AIAgentAttribution(is_ai_agent=True, agent_name="AI Agent", confidence=0.85, evidence=evidence)

    return AIAgentAttribution(is_ai_agent=False)


