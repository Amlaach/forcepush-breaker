_SENSITIVE_CONFIG_PATTERNS = [
    # .env files
    (re.compile(r"(^|/)\.env(\..+)?$", re.IGNORECASE), "env"),
    (re.compile(r".*\.env$", re.IGNORECASE), "env"),
    # Keys and certificates
    (re.compile(r".*\.(pem|key|pkcs12|pfx|p12|keystore|crt|cer|der)$", re.IGNORECASE), "key"),
    (re.compile(r"(^|/)(id_rsa|id_ed25519|id_dsa|id_ecdsa)(_.*)?$", re.IGNORECASE), "key"),
    # Credentials & secrets
    (re.compile(r"(^|/)(credentials|secrets|service[-_]?account.*)\.(json|yaml|yml|toml|ini|xml)$", re.IGNORECASE), "credential"),
    (re.compile(r"(^|/)htpasswd$", re.IGNORECASE), "credential"),
    (re.compile(r".*\.kdbx$", re.IGNORECASE), "credential"),
    # Infrastructure state & variables
    (re.compile(r"(^|/)terraform\.tfstate(\.backup)?$", re.IGNORECASE), "terraform"),
    (re.compile(r".*\.tfvars(\.json)?$", re.IGNORECASE), "terraform"),
    # App configuration with potential secrets
    (re.compile(r"(^|/)(local\.settings\.json|appsettings\..*\.json|config\.(json|yaml|yml))$", re.IGNORECASE), "config"),
]


def classify_sensitive_config_file(file_path: str) -> Optional[str]:
    """Returns the config type category ('env', 'key', 'credential', 'terraform', 'config')

    if file_path matches known sensitive configurations, otherwise None.
    """
    if not file_path:
        return None
    clean_p = file_path.replace("\\", "/").strip()
    for pattern, cat in _SENSITIVE_CONFIG_PATTERNS:
        if pattern.search(clean_p):
            return cat
    return None


def is_sensitive_config_file(file_path: str) -> bool:
    return classify_sensitive_config_file(file_path) is not None


@dataclass
class DeletedConfigFile:
    file_path: str
    file_type: str  # "env" | "key" | "credential" | "terraform" | "config"
    commit_hash: Optional[str] = None
    blob_hash: Optional[str] = None
    size: int = 0
    date: str = ""
    author: str = ""


@dataclass
class DanglingBlob:
    blob_hash: str
    size: int
    content: str
    redacted_content: str = ""
    is_binary: bool = False
    associated_path: Optional[str] = None


@dataclass
class ForensicsScanResult:
    repo_path: str
    is_git_repo: bool
    dangling_commits: List[DanglingCommit] = field(default_factory=list)
    branch_commits: List[DanglingCommit] = field(default_factory=list)
    dangling_blobs: List[DanglingBlob] = field(default_factory=list)
    deleted_config_files: List[DeletedConfigFile] = field(default_factory=list)
    unreachable_trees: List[str] = field(default_factory=list)
    unreachable_tags: List[str] = field(default_factory=list)
    reflog_entries: List[ReflogEntry] = field(default_factory=list)
    repo_metadata: Optional[RepoMetadata] = None
    total_objects_scanned: int = 0
    scan_timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    errors: List[str] = field(default_factory=list)


class GitForensics:
    MAX_BLOB_SIZE_BYTES = 512 * 1024
    MAX_SNAPSHOT_BYTES = 256 * 1024
    MAX_SNAPSHOT_FILES_PER_COMMIT = 25
    MAX_TEXT_SCAN_BYTES = 10 * 1024 * 1024
    GIT_CMD_TIMEOUT_SECONDS = 60

    def __init__(self, repo_path: str | Path = "."):
        self.repo_path = Path(repo_path).resolve()

    def is_valid_repo(self) -> bool:
        if not shutil.which("git"):
            return False
        if not self.repo_path.exists():
            return False
        git_dir = self.repo_path / ".git"
        if git_dir.exists() and (git_dir.is_dir() or git_dir.is_file()):
            return True
        if (self.repo_path / "HEAD").is_file() and (self.repo_path / "objects").is_dir():
            return True
        res = self._run_git(["rev-parse", "--is-inside-work-tree"], check=False)
        if res.returncode == 0 and res.stdout.strip() == "true":
            return True
        bare_res = self._run_git(["rev-parse", "--is-bare-repository"], check=False)
        return bare_res.returncode == 0 and bare_res.stdout.strip() == "true"

    def scan(self) -> ForensicsScanResult:
        if not shutil.which("git"):
            raise RuntimeError(
                "Git executable was not found on the system PATH. "
                "Git is required to perform GitGhost forensics."
            )

        if not self.is_valid_repo():
            return ForensicsScanResult(
                repo_path=str(self.repo_path),
                is_git_repo=False,
                errors=["Specified path is not a valid Git repository."],
            )

        result = ForensicsScanResult(repo_path=str(self.repo_path), is_git_repo=True)
        result.repo_metadata = self.collect_repo_metadata()
        unreachable_objects: Dict[str, Set[str]] = {
            "commit": set(),
            "blob": set(),
            "tree": set(),
            "tag": set(),
        }

        # Step 1: Collect candidates via git fsck
        candidate_hashes: Set[str] = set()

        fsck_res = self._run_git(
            ["fsck", "--full", "--no-reflogs", "--unreachable", "--lost-found"],
            check=False,
        )
        self._parse_fsck_output(
            fsck_res.stdout + "\n" + fsck_res.stderr,
            unreachable_objects,
            candidate_hashes,
        )

        dangling_res = self._run_git(
            ["fsck", "--full", "--no-reflogs", "--dangling"],
            check=False,
        )
        self._parse_fsck_output(
            dangling_res.stdout + "\n" + dangling_res.stderr,
            unreachable_objects,
            candidate_hashes,
        )

        # Inspect .git/lost-found or bare lost-found if present
        for lost_found_dir in (self.repo_path / ".git" / "lost-found", self.repo_path / "lost-found"):
            if lost_found_dir.exists():
                commit_dir = lost_found_dir / "commit"
                if commit_dir.exists() and commit_dir.is_dir():
                    for f in commit_dir.iterdir():
                        if len(f.name) in (40, 64):
                            candidate_hashes.add(f.name)
                            unreachable_objects["commit"].add(f.name)
                other_dir = lost_found_dir / "other"
                if other_dir.exists() and other_dir.is_dir():
                    for f in other_dir.iterdir():
                        if len(f.name) in (40, 64):
                            candidate_hashes.add(f.name)

        result.branch_commits = self.collect_branch_commits(max_commits=60)
        hist_deleted_configs = self.collect_historical_deleted_configs(max_commits=120)

        if not candidate_hashes:
            result.deleted_config_files = hist_deleted_configs
            result.reflog_entries = self.collect_reflog(set())
            return result

        # Step 2: Batch check all candidate objects to identify exact types & sizes in ONE call
        type_and_sizes = self._batch_check(candidate_hashes)
        for obj_hash, (obj_type, size) in type_and_sizes.items():
            if obj_type in unreachable_objects:
                unreachable_objects[obj_type].add(obj_hash)

        result.unreachable_trees = sorted(list(unreachable_objects["tree"]))
        result.unreachable_tags = sorted(list(unreachable_objects["tag"]))

        # Step 3: Reconstruct commits in high-performance batch
        commit_hashes = sorted(list(unreachable_objects["commit"]))
        if commit_hashes:
            result.dangling_commits = self._batch_reconstruct_commits(commit_hashes)
            result.dangling_commits.sort(key=lambda c: c.date, reverse=True)

        # Step 4: Map blob paths from commit trees and unreachable trees
        blob_path_map = self._map_tree_blobs_batch(commit_hashes, unreachable_objects["tree"])

        # Step 5: Read dangling blobs in batch
        blob_hashes = sorted(list(unreachable_objects["blob"]))
        if blob_hashes:
            result.dangling_blobs = self._batch_extract_blobs(
                blob_hashes, type_and_sizes, blob_path_map
            )

        # Step 6: Index deleted sensitive configuration and environment files (Time-Machine)
        config_files_map: Dict[Tuple[str, Optional[str], Optional[str]], DeletedConfigFile] = {}

        for c in result.dangling_commits:
            for fpath in c.changed_files:
                cat = classify_sensitive_config_file(fpath)
                if cat:
                    key = (fpath, c.commit_hash, None)
                    if key not in config_files_map:
                        config_files_map[key] = DeletedConfigFile(
                            file_path=fpath,
                            file_type=cat,
                            commit_hash=c.commit_hash,
                            blob_hash=None,
                            date=c.date,
                            author=c.author,
                        )

        for b in result.dangling_blobs:
            if b.associated_path:
                cat = classify_sensitive_config_file(b.associated_path)
                if cat:
                    key = (b.associated_path, None, b.blob_hash)
                    if key not in config_files_map:
                        config_files_map[key] = DeletedConfigFile(
                            file_path=b.associated_path,
                            file_type=cat,
                            commit_hash=None,
                            blob_hash=b.blob_hash,
                            size=b.size,
                        )

        for hcf in hist_deleted_configs:
            key = (hcf.file_path, hcf.commit_hash, hcf.blob_hash)
            if key not in config_files_map:
                config_files_map[key] = hcf

        result.deleted_config_files = list(config_files_map.values())
        result.reflog_entries = self.collect_reflog(
            {c.commit_hash for c in result.dangling_commits}
        )

        result.total_objects_scanned = (
            len(result.dangling_commits)
            + len(result.dangling_blobs)
            + len(result.unreachable_trees)
            + len(result.unreachable_tags)
        )
        return result

    def _parse_fsck_output(
        self, output: str, bucket: Dict[str, Set[str]], candidate_set: Set[str]
    ) -> None:
        for line in output.splitlines():
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) >= 3 and parts[0] in ("unreachable", "dangling"):
                obj_type = parts[1].lower()
                obj_hash = parts[2]
                candidate_set.add(obj_hash)
                if obj_type in bucket:
                    bucket[obj_type].add(obj_hash)

    def _batch_check(self, hashes: Set[str]) -> Dict[str, Tuple[str, int]]:
        """Invokes 'git cat-file --batch-check' in a single call for all hashes."""
        if not hashes:
            return {}
        p = subprocess.Popen(
            ["git", "cat-file", "--batch-check"],
            cwd=str(self.repo_path),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        stdout, _ = p.communicate("\n".join(hashes) + "\n")
        mapping: Dict[str, Tuple[str, int]] = {}
        for line in stdout.splitlines():
            parts = line.strip().split()
            if len(parts) >= 3:
                obj_hash, obj_type, size_str = parts[0], parts[1].lower(), parts[2]
                try:
                    mapping[obj_hash] = (obj_type, int(size_str))
                except ValueError:
                    mapping[obj_hash] = (obj_type, 0)
        return mapping

    def _batch_reconstruct_commits(self, commit_hashes: List[str]) -> List[DanglingCommit]:
        """Reconstructs commit metadata and diffs using batch log and diff-tree streams."""
        if not commit_hashes:
            return []

        # 1. Batch metadata via git log
        meta_p = subprocess.Popen(
            [
                "git",
                "log",
                "--no-walk",
                "--stdin",
                "--format=%H%x1f%an <%ae>%x1f%aI%x1f%P%x1f%B%x1e",
            ],
            cwd=str(self.repo_path),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        meta_out, _ = meta_p.communicate("\n".join(commit_hashes) + "\n")

        commit_meta: Dict[str, Dict[str, any]] = {}
        for record in meta_out.split("\x1e"):
            rec = record.strip()
            if not rec:
                continue
            fields = rec.split("\x1f")
            h = fields[0].strip()
            commit_meta[h] = {
                "author": fields[1].strip() if len(fields) > 1 and fields[1] else "Unknown",
                "date": fields[2].strip() if len(fields) > 2 and fields[2] else datetime.now(timezone.utc).isoformat(),
                "parents": fields[3].strip().split() if len(fields) > 3 and fields[3] else [],
                "message": fields[4].strip() if len(fields) > 4 else "",
            }

        # 2. Batch diffs via git diff-tree
        diff_p = subprocess.Popen(
            ["git", "diff-tree", "-p", "--root", "--stdin"],
            cwd=str(self.repo_path),
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        diff_out, _ = diff_p.communicate("\n".join(commit_hashes) + "\n")

        commit_hashes_set = set(commit_hashes)
        commit_diffs: Dict[str, str] = {}
        commit_files: Dict[str, List[str]] = {}

        current_commit: Optional[str] = None
        cur_lines: List[str] = []
        cur_files: List[str] = []

        for line in diff_out.splitlines():
            s = line.strip()
            if s in commit_hashes_set:
                if current_commit:
                    commit_diffs[current_commit] = "\n".join(cur_lines)
                    commit_files[current_commit] = list(dict.fromkeys(cur_files))
                current_commit = s
                cur_lines = []
                cur_files = []
            elif current_commit:
                cur_lines.append(line)
                if line.startswith("diff --git a/"):
                    m = re.match(r"^diff --git a/.*? b/(.*)$", line)
                    if m:
                        cur_files.append(m.group(1))

        if current_commit:
            commit_diffs[current_commit] = "\n".join(cur_lines)
            commit_files[current_commit] = list(dict.fromkeys(cur_files))

        reconstructed: List[DanglingCommit] = []
        for ch in commit_hashes:
            meta = commit_meta.get(
                ch,
                {
                    "author": "Unknown",
                    "date": datetime.now(timezone.utc).isoformat(),
                    "parents": [],
                    "message": "",
                },
            )
            meta_author = meta.get("author", "Unknown")
            meta_message = meta.get("message", "")
            diff_text = commit_diffs.get(ch, "")
            ai_attribution = detect_ai_agent(
                author=meta_author,
                message=meta_message,
                diff_content=diff_text,
            )

            reconstructed.append(
                DanglingCommit(
                    commit_hash=ch,
                    author=meta_author,
                    date=meta["date"],
                    message=meta_message,
                    parents=meta["parents"],
                    changed_files=commit_files.get(ch, []),
                    diff_content=diff_text,
                    is_dangling=True,
                    ai_agent=ai_attribution,
                )
            )

        self._batch_populate_commit_snapshots(reconstructed)
        return reconstructed

    def _map_tree_blobs_batch(
        self, commit_hashes: List[str], unreachable_trees: Set[str]
    ) -> Dict[str, str]:
        """Maps blob hashes to their file paths in batch from commit trees and standalone trees."""
        import binascii
        blob_path_map: Dict[str, str] = {}

        if commit_hashes:
            p = subprocess.Popen(
                ["git", "diff-tree", "-r", "--root", "--stdin"],
                cwd=str(self.repo_path),
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                text=True,
                encoding="utf-8",
                errors="replace",
            )
            tree_out, _ = p.communicate("\n".join(commit_hashes) + "\n")
            for line in tree_out.splitlines():
                if "\t" in line:
                    left, path = line.split("\t", 1)
                    parts = left.split()
                    if len(parts) >= 4:
                        b_hash = parts[3]
                        if len(b_hash) in (40, 64) and b_hash != "0" * len(b_hash):
                            blob_path_map[b_hash] = path.strip()

        trees_to_read = [t for t in unreachable_trees if t]
        if trees_to_read:
            p = subprocess.Popen(
                ["git", "cat-file", "--batch"],
                cwd=str(self.repo_path),
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
            )
            raw_input = "\n".join(trees_to_read).encode("ascii") + b"\n"
            raw_output, _ = p.communicate(raw_input)
            stream = io.BytesIO(raw_output)
            while True:
                header_line = stream.readline()
                if not header_line:
                    break
                header_parts = header_line.decode("utf-8", errors="replace").strip().split()
                if len(header_parts) >= 3:
                    try:
                        size = int(header_parts[2])
                    except ValueError:
                        break
                    tree_bytes = stream.read(size)
                    stream.read(1)
                    idx = 0
                    while idx < len(tree_bytes):
                        space_idx = tree_bytes.find(b" ", idx)
                        null_idx = tree_bytes.find(b"\x00", space_idx)
                        if space_idx == -1 or null_idx == -1 or null_idx + 21 > len(tree_bytes):
                            break
                        mode = tree_bytes[idx:space_idx].decode(errors="replace")
                        name = tree_bytes[space_idx + 1:null_idx].decode(errors="replace")
                        sha = binascii.hexlify(tree_bytes[null_idx + 1:null_idx + 21]).decode("ascii")
                        if not mode.startswith("40000"):
                            blob_path_map[sha] = name
                        idx = null_idx + 21
                elif len(header_parts) == 2 and header_parts[1] == "missing":
                    continue
                else:
                    break

        return blob_path_map

    def _batch_extract_blobs(
        self,
        blob_hashes: List[str],
        type_and_sizes: Dict[str, Tuple[str, int]],
        blob_path_map: Dict[str, str],
    ) -> List[DanglingBlob]:
        """Extracts blob contents using a single streamed 'git cat-file --batch' process."""
        blobs: List[DanglingBlob] = []
        readable_hashes: List[str] = []

        for b_hash in blob_hashes:
            size = type_and_sizes.get(b_hash, ("blob", 0))[1]
            path = blob_path_map.get(b_hash)
            if size > self.MAX_BLOB_SIZE_BYTES:
                blobs.append(
                    DanglingBlob(
                        blob_hash=b_hash,
                        size=size,
                        content="[Binary or oversized file content omitted - size: %d bytes]" % size,
                        is_binary=True,
                        associated_path=path,
                    )
                )
            else:
                readable_hashes.append(b_hash)

        if readable_hashes:
            p = subprocess.Popen(
                ["git", "cat-file", "--batch"],
                cwd=str(self.repo_path),
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
            )
            raw_input = b"\n".join(h.encode("ascii") for h in readable_hashes) + b"\n"
            raw_output, _ = p.communicate(raw_input)

            stream = io.BytesIO(raw_output)
            while True:
                header_line = stream.readline()
                if not header_line:
                    break
                header_parts = header_line.decode("utf-8", errors="replace").strip().split()
                if len(header_parts) >= 3:
                    obj_hash, _, size_str = header_parts[0], header_parts[1], header_parts[2]
                    try:
                        size = int(size_str)
                    except ValueError:
                        break
                    raw_data = stream.read(size)
                    stream.read(1)  # trailing newline from git cat-file
                    is_binary = b"\x00" in raw_data[:8000]
                    content = (
                        "[Binary blob data (%d bytes)]" % size
                        if is_binary
                        else raw_data.decode("utf-8", errors="replace")
                    )
                    blobs.append(
                        DanglingBlob(
                            blob_hash=obj_hash,
                            size=size,
                            content=content,
                            is_binary=is_binary,
                            associated_path=blob_path_map.get(obj_hash),
                        )
                    )
                elif len(header_parts) == 2 and header_parts[1] == "missing":
                    continue
                else:
                    break

        return blobs

    def _batch_populate_commit_snapshots(self, commits: List[DanglingCommit]) -> None:
        """Populates bounded full-file text snapshots for changed files in dangling commits via single cat-file batch."""
        queries: List[Tuple[DanglingCommit, str, str]] = []
        for c in commits:
            for fp in c.changed_files[: self.MAX_SNAPSHOT_FILES_PER_COMMIT]:
                if fp and not fp.startswith("/"):
                    spec = f"{c.commit_hash}:{fp}"
                    queries.append((c, fp, spec))

        if not queries:
            return

        try:
            p = subprocess.Popen(
                ["git", "cat-file", "--batch"],
                cwd=str(self.repo_path),
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
            )
            raw_input = "\n".join(q[2] for q in queries).encode("utf-8", errors="replace") + b"\n"
            raw_output, _ = p.communicate(raw_input, timeout=self.GIT_CMD_TIMEOUT_SECONDS)
            stream = io.BytesIO(raw_output)

            for commit_obj, fp, _ in queries:
                header_line = stream.readline()
                if not header_line:
                    break
                header_str = header_line.decode("utf-8", errors="replace").strip()
                if header_str.endswith(" missing"):
                    continue
                parts = header_str.split()
                if len(parts) < 3:
                    break
                obj_type = parts[1].lower()
                try:
                    size = int(parts[2])
                except ValueError:
                    break
                raw_bytes = stream.read(size)
                stream.read(1)  # trailing LF
                if obj_type == "blob" and size <= self.MAX_SNAPSHOT_BYTES and b"\x00" not in raw_bytes[:8000]:
                    commit_obj.file_snapshots[fp] = raw_bytes.decode("utf-8", errors="replace")
        except Exception:
            pass

    def collect_repo_metadata(self) -> RepoMetadata:
        """Collects active branch, HEAD commit, remote origin, working-tree cleanliness, and local branches."""
        meta = RepoMetadata()
        try:
            bare_res = self._run_git(["rev-parse", "--is-bare-repository"], check=False)
            meta.is_bare = bare_res.returncode == 0 and bare_res.stdout.strip() == "true"

            branch_res = self._run_git(["symbolic-ref", "--short", "HEAD"], check=False)
            if branch_res.returncode == 0 and branch_res.stdout.strip():
                meta.current_branch = branch_res.stdout.strip()
            else:
                meta.current_branch = "DETACHED HEAD"

            head_res = self._run_git(["log", "-1", "--format=%H%x1f%s"], check=False)
            if head_res.returncode == 0 and head_res.stdout.strip():
                parts = head_res.stdout.strip().split("\x1f", 1)
                meta.head_sha = parts[0]
                meta.head_subject = parts[1] if len(parts) > 1 else ""

            rem_res = self._run_git(["remote", "get-url", "origin"], check=False)
            if rem_res.returncode == 0 and rem_res.stdout.strip():
                meta.remote_url = rem_res.stdout.strip()

            if not meta.is_bare:
                st_res = self._run_git(["status", "--porcelain"], check=False)
                if st_res.returncode == 0:
                    meta.is_clean = len(st_res.stdout.strip()) == 0

            br_list_res = self._run_git(["for-each-ref", "--format=%(refname:short)", "refs/heads/"], check=False)
            if br_list_res.returncode == 0:
                meta.local_branches = [b.strip() for b in br_list_res.stdout.splitlines() if b.strip()]

            tag_res = self._run_git(["tag", "-l"], check=False)
            if tag_res.returncode == 0:
                meta.tags_count = len([t for t in tag_res.stdout.splitlines() if t.strip()])
        except Exception:
            pass
        return meta

    def collect_reflog(self, dangling_hashes: Set[str], max_entries: int = 80) -> List[ReflogEntry]:
        """Collects structured Git reflog timeline entries to identify resets, rebases, amends, and branch switches."""
        entries: List[ReflogEntry] = []
        try:
            res = self._run_git(
                [
                    "reflog",
                    "show",
                    "HEAD",
                    f"-n{max_entries}",
                    "--date=iso-strict",
                    "--format=%H%x1f%gd%x1f%gs%x1f%an <%ae>%x1f%cd",
                ],
                check=False,
            )
            if res.returncode != 0 or not res.stdout.strip():
                return entries

            for idx, line in enumerate(res.stdout.splitlines()):
                line = line.strip()
                if not line:
                    continue
                parts = line.split("\x1f")
                if len(parts) < 3:
                    continue
                c_hash = parts[0].strip()
                selector = parts[1].strip()
                subject = parts[2].strip()
                author = parts[3].strip() if len(parts) > 3 else "Unknown"
                date_str = parts[4].strip() if len(parts) > 4 else ""

                action = "operation"
                if ":" in subject:
                    action = subject.split(":", 1)[0].strip().lower()

                entries.append(
                    ReflogEntry(
                        index=idx,
                        selector=selector,
                        commit_hash=c_hash,
                        action=action,
                        message=subject,
                        date=date_str,
                        author=author,
                        is_unreachable=c_hash in dangling_hashes,
                    )
                )
        except Exception:
            pass
        return entries

    def list_commit_files(self, commit_hash: str) -> List[Dict[str, Any]]:
        """Lists all files in a commit's tree via 'git ls-tree -r --long <commit>'."""
        clean_sha = (commit_hash or "").strip()
        if not clean_sha:
            return []
        res = self._run_git(["ls-tree", "-r", "--long", clean_sha], check=False)
        if res.returncode != 0:
            return []
        files: List[Dict[str, Any]] = []
        for line in res.stdout.splitlines():
            if "\t" not in line:
                continue
            meta_part, fpath = line.split("\t", 1)
            cols = meta_part.split()
            if len(cols) >= 4:
                try:
                    size = int(cols[3]) if cols[3] != "-" else 0
                except ValueError:
                    size = 0
                files.append({
                    "mode": cols[0],
                    "type": cols[1],
                    "blob_hash": cols[2],
                    "size": size,
                    "path": fpath.strip(),
                })
        return files

    def read_commit_file(self, commit_hash: str, file_path: str) -> Optional[str]:
        """Reads a text file snapshot from a specific commit."""
        clean_sha = (commit_hash or "").strip()
        clean_fp = (file_path or "").strip()
        if not clean_sha or not clean_fp:
            return None
        try:
            res = subprocess.run(
                ["git", "show", f"{clean_sha}:{clean_fp}"],
                cwd=str(self.repo_path),
                capture_output=True,
                timeout=15,
                check=False,
            )
            if res.returncode == 0 and len(res.stdout) <= self.MAX_TEXT_SCAN_BYTES:
                if b"\x00" not in res.stdout[:8000]:
                    return res.stdout.decode("utf-8", errors="replace")
        except Exception:
            pass
        return None

    def read_commit_diff(self, commit_hash: str) -> str:
        """Reads the unified diff patch for any commit SHA."""
        clean_sha = (commit_hash or "").strip()
        if not clean_sha:
            return ""
        res = self._run_git(["show", "--format=", "--patch", "--unified=3", clean_sha], check=False)
        if res.returncode == 0 and res.stdout:
            if len(res.stdout.encode("utf-8", errors="replace")) <= self.MAX_TEXT_SCAN_BYTES:
                return res.stdout
        return ""

    def collect_branch_commits(self, max_commits: int = 60) -> List[DanglingCommit]:
        """Collects recent commits across all branches/tags/PR refs for interactive history browsing."""
        commits: List[DanglingCommit] = []
        try:
            res = self._run_git(
                [
                    "log",
                    "--all",
                    f"-n{max_commits}",
                    "--date=iso-strict",
                    "--name-only",
                    "--format=COMMIT_SEP%x1f%H%x1f%P%x1f%an <%ae>%x1f%cd%x1f%B%x1e",
                ],
                check=False,
            )
            if res.returncode != 0 or not res.stdout:
                return commits

            blocks = res.stdout.split("COMMIT_SEP\x1f")
            for blk in blocks:
                if not blk.strip():
                    continue
                if "\x1e" not in blk:
                    continue
                header_part, files_part = blk.split("\x1e", 1)
                cols = header_part.split("\x1f", 4)
                if len(cols) < 5:
                    continue
                c_hash = cols[0].strip()
                parents = [p for p in cols[1].strip().split() if p]
                author = cols[2].strip()
                date_str = cols[3].strip()
                msg = cols[4].strip()
                changed_files = [ln.strip() for ln in files_part.splitlines() if ln.strip()]

                ai_att = detect_ai_agent(author=author, message=msg)
                commits.append(
                    DanglingCommit(
                        commit_hash=c_hash,
                        author=author,
                        date=date_str,
                        message=msg,
                        redacted_message=msg,
                        parents=parents,
                        changed_files=changed_files,
                        diff_content="",
                        redacted_diff="",
                        is_dangling=False,
                        ai_agent=ai_att,
                    )
                )
        except Exception:
            pass
        return commits

    def collect_historical_deleted_configs(self, max_commits: int = 120) -> List[DeletedConfigFile]:
        """Finds sensitive config/.env files deleted via git rm across commit history, linking to their pre-deletion parent SHA."""
        deleted_items: List[DeletedConfigFile] = []
        seen: Set[Tuple[str, str]] = set()
        try:
            res = self._run_git(
                [
                    "log",
                    "--all",
                    f"-n{max_commits}",
                    "--diff-filter=D",
                    "--date=iso-strict",
                    "--name-only",
                    "--format=DEL_SEP%x1f%H%x1f%P%x1f%an <%ae>%x1f%cd%x1e",
                ],
                check=False,
            )
            if res.returncode != 0 or not res.stdout:
                return deleted_items

            for blk in res.stdout.split("DEL_SEP\x1f"):
                if not blk.strip() or "\x1e" not in blk:
                    continue
                hdr, files_part = blk.split("\x1e", 1)
                cols = hdr.split("\x1f")
                if len(cols) < 4:
                    continue
                parents = cols[1].strip().split()
                if not parents:
                    continue
                parent_sha = parents[0]
                author = cols[2].strip()
                date_str = cols[3].strip()
                for fp in (ln.strip() for ln in files_part.splitlines() if ln.strip()):
                    cat = classify_sensitive_config_file(fp)
                    if cat and (fp, parent_sha) not in seen:
                        seen.add((fp, parent_sha))
                        deleted_items.append(
                            DeletedConfigFile(
                                file_path=fp,
                                file_type=cat,
                                commit_hash=parent_sha,
                                date=date_str,
                                author=author,
                            )
                        )
        except Exception:
            pass
        return deleted_items

    def _run_git(self, args: List[str], check: bool = True) -> subprocess.CompletedProcess[str]:
        full_cmd = ["git"] + args
        try:
            return subprocess.run(
                full_cmd,
                cwd=str(self.repo_path),
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=self.GIT_CMD_TIMEOUT_SECONDS,
                check=check,
            )
        except subprocess.TimeoutExpired:
            if check:
                raise RuntimeError(f"Git command timed out after {self.GIT_CMD_TIMEOUT_SECONDS}s: {' '.join(args)}")
            return subprocess.CompletedProcess(
                args=full_cmd,
                returncode=124,
                stdout="",
                stderr="git command timed out",
            )
        except subprocess.CalledProcessError as e:
            if check:
                raise
            return subprocess.CompletedProcess(
                args=full_cmd,
                returncode=e.returncode,
                stdout=e.stdout or "",
                stderr=e.stderr or "",
            )
        except FileNotFoundError:
            return subprocess.CompletedProcess(
                args=full_cmd,
                returncode=127,
                stdout="",
                stderr="git not found",
            )

